"""Names and rules that define the on-disk layout of a protected archive.

Everything in this module is a *contract with the future*: a trustee in 2036
must be able to recognise these files by name. Change them only with a
format-version bump and a migration note in READ-ME-FIRST.
"""
from __future__ import annotations

import os
import re
import unicodedata
from typing import Optional

FORMAT_VERSION = 1

# Root-level files written by the tool.
SUMS_FILE = "SHA256SUMS"
MANIFEST_FILE = "cold-archive-manifest.json"
README_TXT = "READ-ME-FIRST.txt"
README_HTML = "READ-ME-FIRST.html"
CHECK_COMMAND = "Check-This-Archive.command"

# The folder holding the par2cmdline source (and, on request, a zip of the
# app). It is ordinary payload: hashed, listed, and given its own PARITY set.
TOOLS_DIR = "TOOLS"

# Files that are listed in SHA256SUMS and protected by PARITY-INDEX, in the
# order they are written. SHA256SUMS itself cannot list itself.
ROOT_TOOL_FILES: tuple[str, ...] = (MANIFEST_FILE, README_TXT, README_HTML, CHECK_COMMAND)
ROOT_TOOL_FILE_SET = frozenset(ROOT_TOOL_FILES) | {SUMS_FILE}

# PAR2 set names. A directory's payload is covered by PARITY (and PARITY-2,
# PARITY-3, ... when it has to be split); the root tool files are covered by
# PARITY-INDEX.
PARITY_BASENAME = "PARITY"
INDEX_PARITY_BASENAME = "PARITY-INDEX"
PAR2_SUFFIX = ".par2"

# Matches our own parity files only: PARITY.par2, PARITY-2.vol003+04.par2,
# PARITY-INDEX.par2 ... Foreign .par2 files are treated as ordinary payload.
_PARITY_RE = re.compile(r"^(PARITY(?:-INDEX|-[2-9]|-[1-9][0-9]+)?)(?:\.vol\d+\+\d+)?\.par2$")
# The same names in any letter case. On the default macOS filesystem (and on
# exFAT, FAT and NTFS) "parity.par2" IS "PARITY.par2": a payload file spelled
# that way would be overwritten by our parity file, so such names are refused.
_PARITY_RE_CI = re.compile(_PARITY_RE.pattern, re.IGNORECASE)

# Operating-system litter that must never be archived: it is regenerated by
# the OS, stripped by other filesystems, and would make every verification
# fail for no reason. Deliberately NOT all dotfiles: a user's .git or .htaccess
# is data.
JUNK_NAMES = frozenset({
    ".DS_Store", ".localized", ".Spotlight-V100", ".fseventsd", ".Trashes",
    ".TemporaryItems", ".DocumentRevisions-V100", ".VolumeIcon.icns", ".apdisk",
    ".com.apple.timemachine.donotpresent", ".com.apple.timemachine.supported",
    "Thumbs.db", "desktop.ini", "ehthumbs.db", "$RECYCLE.BIN", "System Volume Information",
})
JUNK_PREFIXES = ("._", ".cold-archive")  # AppleDouble sidecars; our own lock file, temporary build folders and copy temporaries
# Suffix of the temporary files resources.py writes next to a TOOLS/ file.
TOOLS_TMP_SUFFIX = ".cold-archive-tmp"

# Temporary name used while copying, so an interrupted copy never leaves a
# plausible-looking partial file behind.
TMP_SUFFIX = ".coldarchive-partial"
# Advisory lock held by a running job; ignored by the scanner.
LOCK_FILE = ".cold-archive.lock"

# A recorded date and the date on disk count as the same within this many
# seconds. FAT32 keeps dates to 2 s and exFAT to 10 ms, so a copy onto such a
# drive moves every date a little. MEASURED 2026-10-19: with an exact
# comparison, Repair on such a copy took damage for an edit (kept the damaged
# bytes as .1 and said "needs attention"), and Protect asked whether a rotted
# file was changed on purpose, where a yes would record the damage. An edit
# that keeps the size and lands within 2 s of the recorded date is the only
# thing this lets through, and Check, which reads every byte, still finds it.
DATE_SLACK = 2.0


def same_date(a: float, b: float) -> bool:
    return abs(float(a) - float(b)) < DATE_SLACK
# New parity is built inside a hidden folder with this prefix and only moved
# into place once par2 has finished, so an interrupted or failed build never
# leaves a folder without parity.
BUILD_DIR_PREFIX = ".cold-archive-build-"


def is_junk(name: str) -> bool:
    return (name in JUNK_NAMES or name == LOCK_FILE or name.startswith(JUNK_PREFIXES)
            or name.endswith(TMP_SUFFIX) or name.endswith(TOOLS_TMP_SUFFIX))


def parity_set_of(name: str) -> str | None:
    """Return the set name ("PARITY", "PARITY-2", "PARITY-INDEX") if *name* is
    one of our parity files, else None."""
    m = _PARITY_RE.match(name)
    return m.group(1) if m else None


def is_our_parity_file(name: str) -> bool:
    return parity_set_of(name) is not None


def is_our_parity_path(rel: str) -> bool:
    """True for our parity files by relative path: PARITY* sets anywhere, but
    PARITY-INDEX only at the root (a PARITY-INDEX.par2 inside a subfolder is
    somebody's payload, for example a whole archive copied into this one)."""
    name = rel.rsplit("/", 1)[-1]
    s = parity_set_of(name)
    if s is None:
        return False
    return s != INDEX_PARITY_BASENAME or "/" not in rel


def looks_like_our_parity_name(name: str) -> bool:
    """True when *name* is one of our parity names in a different letter case
    (case-folding filesystems would make it the same file as ours)."""
    return parity_set_of(name) is None and _PARITY_RE_CI.match(name) is not None


def is_index_file_of_set(name: str, set_name: str) -> bool:
    return name == set_name + PAR2_SUFFIX


def payload_set_name(index: int) -> str:
    """Set name for the *index*-th (0-based) chunk of a directory's payload."""
    return PARITY_BASENAME if index == 0 else f"{PARITY_BASENAME}-{index + 1}"


def nfc(s: str) -> str:
    """Unicode NFC, for COMPARING names with what par2cmdline prints or stores.
    Never used for what we record: see norm_rel."""
    return unicodedata.normalize("NFC", s)


# MEASURED (macOS 26, exFAT disk image, 2026-09-10): the exFAT driver lists
# every name decomposed (NFD) and opens/stats a file by either spelling, but
# unlink and rename succeed ONLY with the spelling the entry was created with
# (cp from APFS and par2 create NFC entries, a tool writing NFD creates NFD).
# So a file can be un-deletable by the very name the listing gave us. APFS
# accepts both everywhere and hides this; test such code on a real exFAT image.
def _spellings(path: str):
    d, n = os.path.split(path)
    seen = []
    for form in (n, unicodedata.normalize("NFC", n), unicodedata.normalize("NFD", n)):
        if form not in seen:
            seen.append(form)
    return [os.path.join(d, form) for form in seen]


def remove_any_spelling(path: str) -> None:
    """os.remove that also tries the NFC and NFD spellings of the last component."""
    last: Optional[FileNotFoundError] = None
    for cand in _spellings(path):
        try:
            os.remove(cand)
            return
        except FileNotFoundError as e:
            last = e
    raise last if last is not None else FileNotFoundError(path)


def replace_any_spelling(src: str, dst: str) -> None:
    """os.replace that also tries the NFC and NFD spellings of the source's last component."""
    last: Optional[FileNotFoundError] = None
    for cand in _spellings(src):
        try:
            os.replace(cand, dst)
            return
        except FileNotFoundError as e:
            last = e
    raise last if last is not None else FileNotFoundError(src)



def name_problem(name: str) -> Optional[str]:
    """Why a file name cannot be protected by PAR2, or None.

    MEASURED (par2cmdline 1.3.0): a source name containing a backslash is
    silently dropped from the set (exit 0, no warning); a name containing a
    control character (tab, newline, ...) is stored raw but looked up as %XX,
    so the set reports it missing from the moment it is created.
    """
    if "\\" in name:
        return "contains a backslash, which PAR2 cannot store"
    if any(ord(c) < 0x20 or ord(c) == 0x7F for c in name):
        return "contains a control character (tab, newline, ...), which PAR2 cannot store"
    if looks_like_our_parity_name(name):
        return "is one of the archive's own parity file names in a different letter case, which many disks cannot tell apart"
    return None


def norm_rel(rel: str) -> str:
    """Relative path with forward slashes, recorded EXACTLY as the filesystem
    spells it (no Unicode normalisation). macOS looks names up
    normalisation-insensitively, so either form works there; Linux and Windows
    match bytes exactly, so a trustee on those systems can only find a file
    under the spelling that is really on the disk. (Comparisons with par2's
    output use nfc().)"""
    return rel.replace(os.sep, "/")


def is_root_tool_file(rel: str) -> bool:
    return rel in ROOT_TOOL_FILE_SET


def human_bytes(n: float) -> str:
    n = float(n)
    for unit in ("bytes", "KB", "MB", "GB", "TB", "PB"):
        if n < 1000 or unit == "PB":
            return f"{n:.0f} {unit}" if unit == "bytes" else f"{n:.2f} {unit}"
        n /= 1000
    return f"{n:.2f} PB"
